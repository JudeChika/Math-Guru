  Future<void> _solveWithAI() async {
    FocusScope.of(context).unfocus();
    final String inputText = _aiController.text.trim();

    if (inputText.isEmpty && _selectedImage == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text(
              'Please enter a question on Mean or upload a textbook image.'),
        ),
      );
      return;
    }

    setState(() {
      _isLoadingAI = true;
      _result = null;
    });

    try {
      const apiKey = 'AQ.Ab8RN6KkjCtOzLWqngmHJauciZcFBcOm0yrBvlw5O_-NEU_A9w';
      final model = GenerativeModel(model: 'gemini-3.5-flash', apiKey: apiKey);

      final promptText = '''
      You are a strict JSON data extractor for JSS3 Chapter 18 Subtopic 1: Measures of Central Tendency — The Mean (Pages 211–213 & Page 218).
      Classify the user's question into one of these 4 modes:
      - mode 0 (Ungrouped Data List): e.g. "Find the mean of 7, 5, 6, 4, 4, 2, 3, 5, 3, 4" or "6, 7 1/2, 6 1/2, 5, 12, 8" -> mode: 0, input1: "7, 5, 6, 4, 4, 2, 3, 5, 3, 4", input2: "", input3: "", unit: ""
      - mode 1 (Frequency Table): e.g. Score x and Frequency f -> mode: 1, input1: "0, 1, 2, 3, 4, 5" (the scores), input2: "5, 6, 4, 2, 1, 2" (the frequencies), input3: "", unit: ""
      - mode 2 (Missing Value Given Mean): -> mode: 2, input1: "comma-separated known values", input2: "given mean", input3: "total count of items", unit: ""
      - mode 3 (Student x Subject Table like Table 18.4): -> mode: 3, input1: "Name1: s1, s2, s3\\nName2: s1, s2, s3", input2: "Subj1, Subj2, Subj3", input3: "", unit: ""

      Return ONLY valid JSON:
      {
        "mode": 0,
        "input1": "7, 5, 6, 4, 4, 2, 3, 5, 3, 4",
        "input2": "",
        "input3": "",
        "unit": ""
      }
      User Prompt: "$inputText"
      ''';

      final List<Part> parts = [TextPart(promptText)];
      if (_selectedImage != null) {
        final bytes = await _selectedImage!.readAsBytes();
        parts.add(DataPart('image/jpeg', bytes));
      }

      final response = await model.generateContent([Content.multi(parts)]);
      final String rawOutput = (response.text ?? '')
          .trim()
          .replaceAll(RegExp(r'^```[a-zA-Z]*\n'), '')
          .replaceAll(RegExp(r'\n```$'), '')
          .trim();

      final Map<String, dynamic> jsonMap = json.decode(rawOutput);
      if (!mounted) return;

      setState(() {
        _mode = ((jsonMap['mode'] as num?)?.toInt() ?? 0).clamp(0, 3);
        _input1Ctrl.text = (jsonMap['input1'] ?? '').toString();
        _input2Ctrl.text = (jsonMap['input2'] ?? '').toString();
        _input3Ctrl.text = (jsonMap['input3'] ?? '').toString();
        _unitCtrl.text = (jsonMap['unit'] ?? '').toString();
        _inputMode = 1;
      });

      _solveManual();
    } catch (_) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text(
                'AI extraction failed. Please select a textbook preset or use the Manual Builder.'),
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isLoadingAI = false);
      }
    }
  }

  void _solveManual() {
    FocusScope.of(context).unfocus();
    setState(() {
      _result = MeanLogic.solveMean(
        mode: _mode,
        rawInput1: _input1Ctrl.text,
        rawInput2: _input2Ctrl.text,
        rawInput3: _input3Ctrl.text,
        unit: _unitCtrl.text,
      );
    });

    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_result != null && _result!.valid) {
        _canvasTransformController.value = Matrix4.identity();
      }
    });
  }

