class _ExpansionScreenState extends State<ExpansionScreen> {
  int _inputMode = 1; // 0: AI Vision / Question, 1: Manual Builder
  int _mode = 0;
  // 0: Multiply Out a Single Bracket A(B ± C ± D) (Example 1a–c, Ex 7.1 Part A & Rev Ex 7 Part A)
  // 1: Expand and Simplify Two Brackets A(B ± C) ± D(E ± F) (Exercise 7.1 Part B #1, #2, #4, #5, #9–12)
  // 2: Standalone Term Plus/Minus a Bracket M ± A(B ± C) (Exercise 7.1 Part B #3, #6, #7, #8)
  // 3: Universal Free-Form Bracket Expander & Simplifier

  // AI Multimodal Controllers
  final TextEditingController _aiController = TextEditingController();
  bool _isLoadingAI = false;
  XFile? _selectedImage;
  final ImagePicker _picker = ImagePicker();

  // Manual Builder Controllers (All Initialized Completely EMPTY on Launch!)
  final TextEditingController _input1Ctrl = TextEditingController();
  final TextEditingController _input2Ctrl = TextEditingController();
  final TextEditingController _input3Ctrl = TextEditingController();

  ExpansionResult? _result;
  final TransformationController _canvasTransformController =
  TransformationController();

  @override
  void dispose() {
    _aiController.dispose();
    _input1Ctrl.dispose();
    _input2Ctrl.dispose();
    _input3Ctrl.dispose();
    _canvasTransformController.dispose();
    super.dispose();
  }

  void _applyPreset(ExpansionPreset p) {
    setState(() {
      _mode = p.mode;
      _input1Ctrl.text = p.input1;
      _input2Ctrl.text = p.input2;
      _input3Ctrl.text = p.input3;
    });
    _solveManual();
  }

  Future<void> _pickImage(ImageSource source) async {
    try {
      final XFile? image = await _picker.pickImage(source: source);
      if (image != null) {
        setState(() => _selectedImage = image);
      }
    } catch (_) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Failed to pick image.')),
        );
      }
    }
  }

  Future<void> _solveWithAI() async {
    FocusScope.of(context).unfocus();
    final String inputText = _aiController.text.trim();

    if (inputText.isEmpty && _selectedImage == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(
          content: Text(
              'Please enter an algebraic expansion question or upload a textbook image.'),
        ),
      );
      return;
    }

    setState(() {
      _isLoadingAI = true;
      _result = null;
    });

    try {
      const apiKey = 'AQ.Ab8RN6KkjCtOzLWqngmHJauciZcFBcOm0yrBvlw5O_-NEU_A9w';
      final model = GenerativeModel(model: 'gemini-3.8-flash', apiKey: apiKey);

      final promptText = '''
      You are a strict JSON models extractor for JSS3 Chapter 7 Subtopic 1: Expansion of Algebraic Expressions (Pages 65 & 71, Example 1, Exercise 7.1 Parts A & B, and Revision Exercise 7 Part A).
      Extract the algebraic expression to be expanded into "input1" in mode 3 (or mode 0 if a single bracket where "input1" is the outside factor and "input2" is the inside bracket).
      Examples:
      - For "-7(2a - 3b)" -> mode: 0, input1: "-7", input2: "2a - 3b"
      - For "6(y + 3) + 2(y + 5)" -> mode: 3, input1: "6(y + 3) + 2(y + 5)"
      - For "9 - 2(3r - 1)" -> mode: 3, input1: "9 - 2(3r - 1)"

      Return ONLY valid JSON:
      {
        "mode": 0,
        "input1": "-7",
        "input2": "2a - 3b",
        "input3": ""
      }
      User Prompt: "$inputText"
      ''';

      final List<Part> parts = [TextPart(promptText)];
      if (_selectedImage != null) {
        final bytes = await _selectedImage!.readAsBytes();
        parts.add(DataPart('image/jpeg', bytes));
      }

      final response = await model.generateContent([Content.multi(parts)]);
      final String rawOutput = (response.text ?? '')
          .trim()
          .replaceAll(RegExp(r'^```[a-zA-Z]*\n'), '')
          .replaceAll(RegExp(r'\n```$'), '')
          .trim();

      final Map<String, dynamic> jsonMap = json.decode(rawOutput);
      if (!mounted) return;

      setState(() {
        _mode = ((jsonMap['mode'] as num?)?.toInt() ?? 0).clamp(0, 3);
        if (jsonMap['input1'] != null) {
          _input1Ctrl.text = jsonMap['input1'].toString();
        }
        if (jsonMap['input2'] != null) {
          _input2Ctrl.text = jsonMap['input2'].toString();
        }
        if (jsonMap['input3'] != null) {
          _input3Ctrl.text = jsonMap['input3'].toString();
        }
        _inputMode = 1;
      });

      _solveManual();
    } catch (_) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text(
                'AI extraction failed. Please select a textbook preset or use the Manual Builder.'),
          ),
        );
      }
    } finally {
      if (mounted) {
        setState(() => _isLoadingAI = false);
      }
    }
  }

  void _solveManual() {
    FocusScope.of(context).unfocus();
    setState(() {
      if (_mode == 0) {
        _result = ExpansionLogic.solveSingleBracketExpansion(
          outsideFactorStr: _input1Ctrl.text,
          insideBracketStr: _input2Ctrl.text,
        );
      } else if (_mode == 1) {
        final String p1 = _input1Ctrl.text.trim();
        final String p2 = _input2Ctrl.text.trim();
        final String joined = (p2.startsWith('+') || p2.startsWith('-'))
            ? '$p1 $p2'
            : '$p1 + (${p2.replaceAll('(', '').replaceAll(')', '')})';
        final String fullExpr = p1.contains('(') ? joined : '($p1) + ($p2)';
        _result = ExpansionLogic.solveMultiBracketOrStandalone(
          mode: 1,
          rawFullExpression: fullExpr,
        );
      } else if (_mode == 2) {
        final String standalone = _input1Ctrl.text.trim();
        final String mult = _input2Ctrl.text.trim();
        final String inside = _input3Ctrl.text.trim();
        final String multWithSign =
        (mult.startsWith('+') || mult.startsWith('-')) ? mult : '+ $mult';
        _result = ExpansionLogic.solveMultiBracketOrStandalone(
          mode: 2,
          rawFullExpression: '$standalone $multWithSign($inside)',
        );
      } else {
        _result = ExpansionLogic.solveMultiBracketOrStandalone(
          mode: 3,
          rawFullExpression: _input1Ctrl.text,
        );
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_result != null && _result!.valid) {
        _canvasTransformController.value = Matrix4.identity();
      }
    });
  }

