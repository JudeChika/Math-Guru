          verticalSideRaw: _input1Ctrl.text,
          horizontalSideRaw: _input2Ctrl.text,
          angle1SymbolRaw: _input3Ctrl.text,
          angle2SymbolRaw: _input4Ctrl.text,
        );
      }
    });

    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (_result != null && _result!.valid) {
        _canvasTransformController.value = Matrix4.identity();
      }
    });
  }

