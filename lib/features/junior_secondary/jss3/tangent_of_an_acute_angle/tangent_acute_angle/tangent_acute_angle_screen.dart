    FocusScope.of(context).unfocus();
    setState(() {
      if (_mode == 0) {
        _result = TangentAcuteAngleLogic.solveFromTriangleVertices(
          triVerticesRaw: _input1Ctrl.text,
          rightAngleVertexRaw: _input2Ctrl.text,
          acuteAngleVertexRaw: _input3Ctrl.text,
          angleSymbolRaw: _input4Ctrl.text,
        );
      } else if (_mode == 1) {
        _result = TangentAcuteAngleLogic.solveFromSingleLetterSides(
          oppLetterRaw: _input1Ctrl.text,
          adjLetterRaw: _input2Ctrl.text,
          hypLetterRaw: _input3Ctrl.text,
