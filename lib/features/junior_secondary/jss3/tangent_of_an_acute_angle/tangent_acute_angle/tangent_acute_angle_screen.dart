/// CustomPainter replicating Fig. 14.2 (Page 143) with color-coded Opposite, Adjacent, and Hypotenuse labels & arrows!
class _RightTriangleAnatomyPainter extends CustomPainter {
  final TangentAcuteAngleCanvasData data;

  _RightTriangleAnatomyPainter(this.data);

  @override
  void paint(Canvas canvas, Size size) {
    final Offset ptTop = Offset(size.width * 0.28, 22);
    final Offset ptRightAng = Offset(size.width * 0.28, size.height - 28);
    final Offset ptBase = Offset(size.width * 0.76, size.height - 28);

    final Path triPath = Path()
      ..moveTo(ptTop.dx, ptTop.dy)
      ..lineTo(ptRightAng.dx, ptRightAng.dy)
      ..lineTo(ptBase.dx, ptBase.dy)
      ..close();

    canvas.drawPath(
      triPath,
      Paint()
        ..color = Colors.deepPurple.withValues(alpha: 0.10)
        ..style = PaintingStyle.fill,
    );

    // Draw Opposite side (Vertical left: Deep Purple)
    canvas.drawLine(
      ptTop,
      ptRightAng,
      Paint()
        ..color = Colors.deepPurple
        ..strokeWidth = 2.8,
    );

    // Draw Adjacent side (Horizontal bottom: Teal)
    canvas.drawLine(
      ptRightAng,
      ptBase,
      Paint()
        ..color = Colors.teal.shade700
        ..strokeWidth = 2.8,
    );

    // Draw Hypotenuse (Slanted: Orange)
    canvas.drawLine(
      ptTop,
      ptBase,
      Paint()
        ..color = Colors.orange.shade800
        ..strokeWidth = 2.5,
    );

    // Draw 90° right-angle square symbol at ptRightAng
    const double sq = 13.0;
    final Path rightSq = Path()
      ..moveTo(ptRightAng.dx, ptRightAng.dy - sq)
      ..lineTo(ptRightAng.dx + sq, ptRightAng.dy - sq)
      ..lineTo(ptRightAng.dx + sq, ptRightAng.dy);
    canvas.drawPath(
      rightSq,
      Paint()
        ..color = Colors.black87
        ..strokeWidth = 1.6
        ..style = PaintingStyle.stroke,
    );

    // Draw acute angle arc at ptBase
    final double hypAngle =
    math.atan2(ptTop.dy - ptBase.dy, ptTop.dx - ptBase.dx);
    canvas.drawArc(
      Rect.fromCenter(center: ptBase, width: 46, height: 46),
      math.pi,
      hypAngle - math.pi,
      false,
      Paint()
        ..color = Colors.red.shade700
        ..strokeWidth = 2.0
        ..style = PaintingStyle.stroke,
    );

    void drawLabel(String text, Offset pos, Color color,
        {double fontSize = 12.0}) {
      if (text.isEmpty) return;
      final TextPainter tp = TextPainter(
        text: TextSpan(
          text: text,
          style: TextStyle(
            color: color,
            fontSize: fontSize,
            fontWeight: FontWeight.bold,
          ),
        ),
        textDirection: TextDirection.ltr,
      )..layout();
      tp.paint(canvas, Offset(pos.dx - tp.width / 2, pos.dy - tp.height / 2));
    }

    // Vertex labels
    drawLabel(data.topVertex, Offset(ptTop.dx - 12, ptTop.dy - 6),
        Colors.deepPurple.shade900,
        fontSize: 13);
    drawLabel(
        data.rightAngleVertex,
        Offset(ptRightAng.dx - 12, ptRightAng.dy + 8),
        Colors.black87,
        fontSize: 13);
    drawLabel(data.baseVertex, Offset(ptBase.dx + 12, ptBase.dy + 6),
        Colors.red.shade900,
        fontSize: 13);

    // Acute angle label inside arc
    drawLabel(data.angleLabel, Offset(ptBase.dx - 34, ptBase.dy - 12),
        Colors.red.shade800,
        fontSize: 12.5);

    // Side role labels (matching Fig. 14.2 on Page 143!)
    drawLabel(
      data.oppSideLabel,
      Offset(ptTop.dx - 58, (ptTop.dy + ptRightAng.dy) / 2),
      Colors.deepPurple.shade900,
    );
    drawLabel(
      data.adjSideLabel,
      Offset((ptRightAng.dx + ptBase.dx) / 2, ptRightAng.dy + 15),
      Colors.teal.shade900,
    );
    drawLabel(
      data.hypSideLabel,
      Offset((ptTop.dx + ptBase.dx) / 2 + 52, (ptTop.dy + ptBase.dy) / 2 - 8),
      Colors.orange.shade900,
    );
  }

  @override
  bool shouldRepaint(covariant _RightTriangleAnatomyPainter oldDelegate) =>
      true;
}

