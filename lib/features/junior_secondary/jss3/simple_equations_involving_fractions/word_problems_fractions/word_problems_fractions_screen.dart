    });

    try {
      const apiKey = 'AQ.Ab8RN6KkjCtOzLWqngmHJauciZcFBcOm0yrBvlw5O_-NEU_A9w';
      final model = GenerativeModel(model: 'gemini-3.5-flash', apiKey: apiKey);

      final promptText = '''
      You are a strict JSON models extractor and translator for JSS3 Chapter 9 Subtopic 4: Word Problems Involving Algebraic Fractions (Pages 86–89, Example 5a–e & Exercise 9.4 #1–20).
      Given the user's word problem or image:
      1. Put the full word problem text into "problemStatement".
      2. Put what the unknown variable represents into "unknownMeaning" (e.g. "the unknown number" or "Adamu's monthly allowance").
      3. Translate the word problem into a clean fractional linear equation in one variable (e.g. "(x + 2)/3 = (3x - 5)/8", "1/m + 1/2m = 1/5", "3x/5 + x/4 = x - 330") and place it in "equationStr".

      Return ONLY valid JSON:
      {
        "mode": 3,
        "problemStatement": "Bello thinks of a number...",
        "unknownMeaning": "the unknown number",
        "equationStr": "(x + 2)/3 = (3x - 5)/8"
      }
      User Prompt: "$inputText"
      ''';

      final List<Part> parts = [TextPart(promptText)];
      if (_selectedImage != null) {
        final bytes = await _selectedImage!.readAsBytes();
        parts.add(DataPart('image/jpeg', bytes));
      }

      final response = await model.generateContent([Content.multi(parts)]);
      final String rawOutput = (response.text ?? '')
          .trim()
          .replaceAll(RegExp(r'^```[a-zA-Z]*\n'), '')
          .replaceAll(RegExp(r'\n```$'), '')
          .trim();

      final Map<String, dynamic> jsonMap = json.decode(rawOutput);
      if (!mounted) return;

      setState(() {
        _mode = ((jsonMap['mode'] as num?)?.toInt() ?? 3).clamp(0, 4);
        _statementCtrl.text = (jsonMap['problemStatement'] ?? '').toString();
        _meaningCtrl.text = (jsonMap['unknownMeaning'] ?? '').toString();
